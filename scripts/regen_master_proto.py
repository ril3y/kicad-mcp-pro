"""Regenerate vendored master KiCad proto stubs from `kicad-source/api/proto/`.

Closes task #86. Run this whenever upstream `kicad-source/api/proto/*.proto`
changes (new IPC commands added, message shape changes, etc.) — the
generated `_pb2.py` files under `src/kicad_mcp/_master_proto/mp/` must
be regenerated to expose the new types.

The vendoring scheme:
  * `kicad-source/api/proto/<area>/<file>.proto` is staged at
    `<staging>/mp/<area>/<file>.proto` so the resulting descriptor pool
    entries are `mp/<area>/...` instead of `<area>/...` — avoids
    collision with kipy's older `<area>/...` protos.
  * Each staged proto has its `import "common/..."` / `import
    "schematic/..."` / `import "board/..."` lines rewritten to prepend
    `mp/`.
  * Generated `_pb2.py` files have their descriptor registration
    rerouted from `descriptor_pool.Default()` → our `_shared_pool` (see
    `_master_proto/_pool.py`) so all master protos live in one private
    pool that doesn't pollute kipy's default pool.

Usage:
    uv run python scripts/regen_master_proto.py

Requires a tempvenv with grpcio-tools installed (this script bootstraps
one if absent so it never touches the project's running venv, which is
often locked by an attached MCP subprocess).

Re-run is idempotent — overwrites files in place. Diff the result
against HEAD before committing to confirm only the intended changes
landed.
"""

from __future__ import annotations

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
KICAD_SOURCE_PROTO = pathlib.Path(r"X:\Projects\kicad-source\api\proto")
DEST_TREE = REPO_ROOT / "src" / "kicad_mcp" / "_master_proto" / "mp"

IMPORT_REWRITE = re.compile(r'^import "((?:common|schematic|board)/)', re.M)


def _bootstrap_protoc_venv() -> pathlib.Path:
    """Create or reuse a temp venv with grpcio-tools + protobuf 5.x.

    Pinned to protobuf<6 because the project's runtime is on 5.27 and
    pb2 files generated by 6.x reject earlier runtimes via
    `ValidateProtobufRuntimeVersion`.
    """
    venv_dir = pathlib.Path(tempfile.gettempdir()) / "kicad_mcp_protoc_venv"
    python = venv_dir / "Scripts" / "python.exe"
    if not python.exists():
        uv = shutil.which("uv") or r"C:\Users\riley\.local\bin\uv.exe"
        subprocess.run([uv, "venv", "--python", "3.12", str(venv_dir)], check=True)
        subprocess.run(
            [uv, "pip", "install", "--python", str(python), "grpcio-tools", "protobuf>=5.27,<6"],
            check=True,
        )
    return python


def _stage_protos(staging: pathlib.Path) -> None:
    target = staging / "mp"
    target.mkdir(parents=True, exist_ok=True)
    for src in KICAD_SOURCE_PROTO.iterdir():
        dst = target / src.name
        if src.is_dir():
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
    for proto in target.rglob("*.proto"):
        text = proto.read_text()
        new = IMPORT_REWRITE.sub(r'import "mp/\1', text)
        if new != text:
            proto.write_text(new)


def _run_protoc(python: pathlib.Path, staging: pathlib.Path, out: pathlib.Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    protos = sorted((staging / "mp").rglob("*.proto"))
    subprocess.run(
        [
            str(python),
            "-m",
            "grpc_tools.protoc",
            f"--proto_path={staging}",
            f"--python_out={out}",
            f"--pyi_out={out}",
            *[str(p) for p in protos],
        ],
        check=True,
    )


def _patch_shared_pool(generated: pathlib.Path) -> None:
    """Reroute every regenerated `_pb2.py` from `descriptor_pool.Default()`
    to our private `_shared_pool` so master protos don't pollute kipy's pool.
    """
    needle_import = "from google.protobuf import descriptor_pool as _descriptor_pool\n"
    add_import = (
        needle_import + "from kicad_mcp._master_proto._pool import shared_pool as _shared_pool\n"
    )
    needle_call = "DESCRIPTOR = _descriptor_pool.Default().AddSerializedFile("
    new_call = "DESCRIPTOR = _shared_pool.AddSerializedFile("
    for pb2 in generated.rglob("*_pb2.py"):
        text = pb2.read_text()
        if needle_call not in text:
            continue
        pb2.write_text(text.replace(needle_import, add_import).replace(needle_call, new_call))


def _install(generated: pathlib.Path) -> None:
    """Mirror generated files into the vendored tree, preserving __init__ scaffolding."""
    src_root = generated / "mp"
    for src in src_root.rglob("*"):
        if src.is_dir():
            continue
        rel = src.relative_to(src_root)
        dst = DEST_TREE / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)


def main() -> None:
    if not KICAD_SOURCE_PROTO.is_dir():
        sys.exit(f"kicad-source proto tree not found at {KICAD_SOURCE_PROTO}")
    python = _bootstrap_protoc_venv()
    with tempfile.TemporaryDirectory(prefix="kicad_mcp_proto_") as tmp:
        staging = pathlib.Path(tmp) / "src"
        out = pathlib.Path(tmp) / "out"
        _stage_protos(staging)
        _run_protoc(python, staging, out)
        _patch_shared_pool(out)
        _install(out)
    print(f"Regenerated proto stubs under {DEST_TREE}")
    print("Restart any running MCP server / Python process to pick up new modules.")


if __name__ == "__main__":
    main()
